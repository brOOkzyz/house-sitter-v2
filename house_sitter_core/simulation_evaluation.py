"""Deterministic, offline evaluation of the simulation-only sequence state machine."""

from __future__ import annotations

import csv
import io
import json
import os
import shutil
import tempfile
from pathlib import Path
from typing import Any

from .simulation_sequence import (
    DEFAULT_SEQUENCE,
    SimulationSequenceError,
    build_simulation_sequence,
    load_sequence_inputs,
)


class SimulationEvaluationError(ValueError):
    """Raised when an offline evaluation cannot be safely constructed."""


SCENARIO_ORDER = ("baseline_success", "simulated_failure", "simulated_timeout", "user_cancel")
EVALUATION_SEQUENCE = DEFAULT_SEQUENCE
TRIAL_FIELDS = (
    "scenario", "trial_index", "overall_status", "total_steps", "succeeded_steps", "failed_steps",
    "timed_out_steps", "cancelled_steps", "terminal_label", "terminal_reason",
    "living_room_status", "kitchen_status", "bedroom_status", "charging_area_status",
)
SUMMARY_FIELDS = (
    "scenario", "trials", "expected_overall_status", "matching_trials", "mismatching_trials",
    "success_rate", "failed_rate", "timed_out_rate", "cancelled_rate", "deterministic",
)
STATUSES = ("succeeded", "failed", "timed_out", "cancelled")


def _validate_trials(value: Any) -> int:
    if isinstance(value, bool) or not isinstance(value, int) or value <= 0:
        raise SimulationEvaluationError("trials-per-scenario must be a positive integer.")
    return value


def _require_synthetic_demo(document: dict[str, Any], records_key: str, name: str) -> None:
    """Keep this evaluator scoped to structurally valid local synthetic-demo data.

    This checks schema-like flags and internal consistency only.  It does not
    authenticate the file's provenance or establish that it was generated by
    a particular selector process.
    """
    if document.get("demo_only") is not True or document.get("synthetic_semantics") is not True or document.get("ground_truth") is not False:
        raise SimulationEvaluationError(f"{name} must be an explicit synthetic demo artifact.")
    records = document.get(records_key)
    if not isinstance(records, list):
        raise SimulationEvaluationError(f"{name} records must be a list.")
    for record in records:
        if not isinstance(record, dict) or record.get("demo_only") is not True or record.get("synthetic_semantics") is not True or record.get("ground_truth") is not False:
            raise SimulationEvaluationError(f"{name} record must be an explicit synthetic demo record.")


def _scenarios() -> tuple[dict[str, Any], ...]:
    return (
        {"name": "baseline_success", "expected": "succeeded", "controls": {},
         "pattern": {"living_room": "succeeded", "kitchen": "succeeded", "bedroom": "succeeded", "charging_area": "succeeded"}},
        {"name": "simulated_failure", "expected": "failed", "controls": {"fail_label": "kitchen"},
         "pattern": {"living_room": "succeeded", "kitchen": "failed", "bedroom": "cancelled", "charging_area": "cancelled"}},
        {"name": "simulated_timeout", "expected": "timed_out", "controls": {"timeout_seconds": 5.0, "step_durations": {"bedroom": 8.0}},
         "pattern": {"living_room": "succeeded", "kitchen": "succeeded", "bedroom": "timed_out", "charging_area": "cancelled"}},
        {"name": "user_cancel", "expected": "cancelled", "controls": {"cancel_before_label": "bedroom"},
         "pattern": {"living_room": "succeeded", "kitchen": "succeeded", "bedroom": "cancelled", "charging_area": "cancelled"}},
    )


def _terminal(result: dict[str, Any]) -> tuple[str, str]:
    overall = result["overall_status"]
    if overall == "succeeded":
        return "", ""
    for step in result["steps"]:
        if step["status"] == overall or (overall == "cancelled" and step["terminal_reason"] == "user_requested_cancel"):
            return step["label"], step["terminal_reason"]
    raise SimulationEvaluationError("result has no terminal step for its overall status.")


def _trial_row(scenario: str, trial_index: int, result: dict[str, Any]) -> dict[str, Any]:
    by_label = {step["label"]: step["status"] for step in result["steps"]}
    terminal_label, terminal_reason = _terminal(result)
    return {
        "scenario": scenario, "trial_index": trial_index, "overall_status": result["overall_status"],
        "total_steps": result["total_steps"], "succeeded_steps": result["succeeded_steps"],
        "failed_steps": result["failed_steps"], "timed_out_steps": result["timed_out_steps"],
        "cancelled_steps": result["cancelled_steps"], "terminal_label": terminal_label, "terminal_reason": terminal_reason,
        **{f"{label}_status": by_label[label] for label in DEFAULT_SEQUENCE},
    }


def _csv(fields: tuple[str, ...], rows: list[dict[str, Any]]) -> str:
    stream = io.StringIO(newline="")
    writer = csv.DictWriter(stream, fieldnames=fields, lineterminator="\n", extrasaction="raise")
    writer.writeheader(); writer.writerows(rows)
    return stream.getvalue()


def _rate(rows: list[dict[str, Any]], status: str) -> float:
    return sum(row["overall_status"] == status for row in rows) / len(rows)


def _summary_row(scenario: dict[str, Any], rows: list[dict[str, Any]], deterministic: bool) -> dict[str, Any]:
    matches = sum(row["overall_status"] == scenario["expected"] for row in rows)
    return {
        "scenario": scenario["name"], "trials": len(rows), "expected_overall_status": scenario["expected"],
        "matching_trials": matches, "mismatching_trials": len(rows) - matches,
        "success_rate": _rate(rows, "succeeded"), "failed_rate": _rate(rows, "failed"),
        "timed_out_rate": _rate(rows, "timed_out"), "cancelled_rate": _rate(rows, "cancelled"),
        "deterministic": str(deterministic).lower(),
    }


def _svg(summary: list[dict[str, Any]]) -> str:
    width, height, baseline, chart_height = 960, 440, 350, 250
    max_count = max(int(row["trials"]) for row in summary)
    colors = {"succeeded": "#268bd2", "failed": "#dc322f", "timed_out": "#b58900", "cancelled": "#6c71c4"}
    lines = [
        '<?xml version="1.0" encoding="UTF-8"?>',
        f'<svg xmlns="http://www.w3.org/2000/svg" width="{width}" height="{height}" viewBox="0 0 {width} {height}">',
        '<rect width="960" height="440" fill="#ffffff"/>',
        '<text x="480" y="30" text-anchor="middle" font-family="DejaVu Sans" font-size="20">Simulation-only status counts</text>',
        f'<line x1="70" y1="{baseline}" x2="920" y2="{baseline}" stroke="#333"/>',
        '<text x="18" y="205" font-family="DejaVu Sans" font-size="12" transform="rotate(-90 18 205)">trial count</text>',
    ]
    for index, row in enumerate(summary):
        x = 105 + index * 210
        rate_fields = {"succeeded": "success_rate", "failed": "failed_rate", "timed_out": "timed_out_rate", "cancelled": "cancelled_rate"}
        counts = {status: round(float(row[rate_fields[status]]) * int(row["trials"])) for status in STATUSES}
        for status_index, status in enumerate(STATUSES):
            value = counts[status]; bar_height = 0 if max_count == 0 else chart_height * value / max_count
            bar_x = x + status_index * 30
            lines.append(f'<rect x="{bar_x}" y="{baseline - bar_height:.3f}" width="22" height="{bar_height:.3f}" fill="{colors[status]}"/>')
            lines.append(f'<text x="{bar_x + 11}" y="{baseline - bar_height - 5:.3f}" text-anchor="middle" font-family="DejaVu Sans" font-size="11">{value}</text>')
        lines.append(f'<text x="{x + 43}" y="375" text-anchor="middle" font-family="DejaVu Sans" font-size="12">{row["scenario"]}</text>')
    for index, status in enumerate(STATUSES):
        x = 160 + index * 155
        lines.append(f'<rect x="{x}" y="405" width="14" height="14" fill="{colors[status]}"/>')
        lines.append(f'<text x="{x + 20}" y="417" font-family="DejaVu Sans" font-size="12">{status}</text>')
    return "\n".join(lines + ["</svg>", ""])


def _report(trials: int, summary: list[dict[str, Any]]) -> str:
    rows = [
        "# Simulation-only Evaluation Report", "", "## Scope and Safety Boundary", "",
        "Synthetic demo labels; not ground truth; simulation/review only; robot motion disabled.",
        "No ROS/Nav2 command execution occurs. Failures, timeouts, and cancellation are injected simulation events.",
        "Evaluation accepts structurally valid and internally consistent selector-style artifacts; it does not authenticate file provenance.", "",
        "## Experiment Configuration", "", f"- Fixed sequence: `{', '.join(EVALUATION_SEQUENCE)}`", f"- Trials per scenario: {trials}",
        "- baseline_success: no injected terminal event", "- simulated_failure: fail_label = kitchen",
        "- simulated_timeout: timeout_seconds = 5, bedroom step_duration = 8", "- user_cancel: cancel_before_label = bedroom", "",
        "## Results", "", "| scenario | trials | expected status | matching trials | success | failed | timed out | cancelled | deterministic |",
        "| --- | ---: | --- | ---: | ---: | ---: | ---: | ---: | --- |",
    ]
    for row in summary:
        rows.append(f"| {row['scenario']} | {row['trials']} | {row['expected_overall_status']} | {row['matching_trials']} | {float(row['success_rate']):.1f} | {float(row['failed_rate']):.1f} | {float(row['timed_out_rate']):.1f} | {float(row['cancelled_rate']):.1f} | {row['deterministic']} |")
    rows += ["", "## Interpretation", "", "The deterministic simulation-only state machine matched its configured expectations. Injected failure, timeout, and cancellation terminal states correctly cancelled downstream steps. These results are not robot navigation, Nav2, dynamic-obstacle, room-semantics, or real fault-detection performance claims.", ""]
    return "\n".join(rows)


def evaluate(regions_document: dict[str, Any], goals_document: dict[str, Any], trials_per_scenario: int = 10) -> dict[str, str]:
    trials = _validate_trials(trials_per_scenario)
    _require_synthetic_demo(regions_document, "regions", "semantic regions")
    _require_synthetic_demo(goals_document, "goals", "safe goals")
    # One preflight call reuses the strict artifact identity, provenance, flags, and selector-evidence contract.
    try:
        plan, _ = build_simulation_sequence(regions_document, goals_document, EVALUATION_SEQUENCE)
    except SimulationSequenceError as exc:
        raise SimulationEvaluationError(str(exc)) from exc
    trial_rows: list[dict[str, Any]] = []; summary_rows: list[dict[str, Any]] = []; scenario_json: dict[str, Any] = {}
    for scenario in _scenarios():
        rows: list[dict[str, Any]] = []; serializations: list[str] = []
        for trial_index in range(1, trials + 1):
            try:
                _, result = build_simulation_sequence(regions_document, goals_document, EVALUATION_SEQUENCE, **scenario["controls"])
            except SimulationSequenceError as exc:
                raise SimulationEvaluationError(str(exc)) from exc
            row = _trial_row(scenario["name"], trial_index, result); rows.append(row); trial_rows.append(row)
            serializations.append(json.dumps(result, sort_keys=True, separators=(",", ":")))
        deterministic = len(set(serializations)) == 1
        summary = _summary_row(scenario, rows, deterministic); summary_rows.append(summary)
        counts = {status: sum(row[f"{label}_status"] == status for row in rows for label in DEFAULT_SEQUENCE) for status in STATUSES}
        scenario_json[scenario["name"]] = {
            "expected_overall_status": scenario["expected"], "trials": trials,
            "matching_trials": summary["matching_trials"], "mismatching_trials": summary["mismatching_trials"],
            "status_counts": counts, "step_status_pattern": scenario["pattern"], "deterministic": deterministic,
        }
    provenance = [{field: step[field] for field in ("label", "proposal_id", "partition_id", "source_candidate_order", "source_selection_rank", "demo_assignment_order", "goal_order")} for step in plan["steps"]]
    summary_json = {
        "schema_version": "1.0", "sequence": list(EVALUATION_SEQUENCE), "trials_per_scenario": trials,
        "total_trials": len(trial_rows), "scenario_order": list(SCENARIO_ORDER), "scenarios": scenario_json,
        "overall_contract_passed": all(row["mismatching_trials"] == 0 and row["deterministic"] == "true" for row in summary_rows),
        "map_identity": plan["map_identity"], "provenance_summary": provenance,
    }
    return {
        "evaluation_trials.csv": _csv(TRIAL_FIELDS, trial_rows),
        "evaluation_summary.csv": _csv(SUMMARY_FIELDS, summary_rows),
        "evaluation_summary.json": json.dumps(summary_json, indent=2) + "\n",
        "evaluation_report.md": _report(trials, summary_rows),
        "evaluation_status_counts.svg": _svg(summary_rows),
    }


def evaluate_paths(regions_path: Path, goals_path: Path, trials_per_scenario: int = 10) -> dict[str, str]:
    try:
        regions, goals = load_sequence_inputs(Path(regions_path), Path(goals_path))
    except SimulationSequenceError as exc:
        raise SimulationEvaluationError(str(exc)) from exc
    return evaluate(regions, goals, trials_per_scenario)


def _cleanup_temporary(temporary: Path) -> OSError | None:
    """Best-effort cleanup that preserves a pre-existing primary exception."""
    try:
        shutil.rmtree(temporary)
        return None
    except OSError as cleanup_error:
        # Generated evaluation directories contain only five regular files.
        try:
            for child in temporary.iterdir():
                child.unlink()
            temporary.rmdir()
        except OSError as fallback_error:
            cleanup_error.add_note(f"fallback temporary cleanup also failed: {fallback_error}")
        return cleanup_error


def write_evaluation(output_dir: Path, contents: dict[str, str]) -> None:
    expected = {"evaluation_trials.csv", "evaluation_summary.csv", "evaluation_summary.json", "evaluation_report.md", "evaluation_status_counts.svg"}
    if set(contents) != expected:
        raise SimulationEvaluationError("evaluation output set is incomplete.")
    output = Path(output_dir)
    if output.exists():
        raise SimulationEvaluationError(f"evaluation output directory already exists: {output}")
    temporary: Path | None = None; published = False; primary_error: BaseException | None = None
    try:
        output.parent.mkdir(parents=True, exist_ok=True)
        temporary = Path(tempfile.mkdtemp(prefix=f".{output.name}.tmp-", dir=output.parent))
        for name in ("evaluation_trials.csv", "evaluation_summary.csv", "evaluation_summary.json", "evaluation_report.md", "evaluation_status_counts.svg"):
            (temporary / name).write_text(contents[name], encoding="utf-8", newline="")
        os.replace(temporary, output); published = True
    except BaseException as exc:
        # Deliberately re-raise KeyboardInterrupt and SystemExit unchanged.
        primary_error = exc
        raise
    finally:
        if not published and temporary is not None and temporary.exists():
            cleanup_error = _cleanup_temporary(temporary)
            if cleanup_error is not None:
                if primary_error is not None:
                    primary_error.add_note(f"temporary cleanup failed: {cleanup_error}")
                else:
                    raise cleanup_error
